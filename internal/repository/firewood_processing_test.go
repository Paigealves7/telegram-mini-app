func TestFirewoodLifecycle(t *testing.T) {
	url := os.Getenv("FIREWOOD_TEST_DATABASE_URL")
	if url == "" {
		t.Skip("isolated firewood database required")
	}
	ctx := context.Background()
	db, err := pgxpool.New(ctx, url)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	r := NewRepository(db)
	org, err := r.CreateOrganization(ctx, "Тестовые дрова", "", true)
	if err != nil {
		t.Fatal(err)
	}

	var uid, cid int64
	if err = db.QueryRow(ctx, `INSERT INTO users(username,password_hash,role) VALUES('firewood-test','test','manager') RETURNING id`).Scan(&uid); err != nil {
		t.Fatal(err)
	}
	if err = db.QueryRow(ctx, `INSERT INTO contractors(organization_id, name) VALUES($1, 'firewood-test') RETURNING id`, org.ID).Scan(&cid); err != nil {
		t.Fatal(err)
	}
	if _, err = r.CreateFirewoodArrival(ctx, org.ID, cid, cid, "test", 10, "2026-11-14", uid); err != nil {
		t.Fatal(err)
	}
	p := domain.FirewoodProcessing{Kind: "split", VolumeM3: 3, Performer: "Рабочий", Date: "2026-11-14"}
	if err = r.CreateFirewoodProcessing(ctx, org.ID, &p, uid); err != nil {
		t.Fatal(err)
	}
	if math.Abs(p.RawM3-1.65) > 1e-9 {
		t.Fatalf("raw=%v", p.RawM3)
	}
	q := p
	q.Kind = "round"
	if err = r.CreateFirewoodProcessing(ctx, org.ID, &q, uid); err != nil {
		t.Fatal(err)
	}
	if math.Abs(q.RawM3-1.8) > 1e-9 {
		t.Fatalf("raw=%v", q.RawM3)
	}
	if err = r.UpdateFirewoodSettings(ctx, org.ID, .7, .8); err != nil {
		t.Fatal(err)
	}
	list, err := r.FirewoodProcessing(ctx, org.ID, 100, 0)
	if err != nil || len(list) != 2 || list[1].Coefficient != .55 {
		t.Fatalf("history: %v %v", list, err)
	}
	s, err := r.GetFirewoodStock(ctx, org.ID)
	if err != nil || math.Abs(s.RawM3-6.55) > 1e-9 || s.SplitM3 != 3 || s.RoundM3 != 3 {
		t.Fatalf("stock: %+v %v", s, err)
	}
	q.VolumeM3 = 100
	if err = r.CreateFirewoodProcessing(ctx, org.ID, &q, uid); !errors.Is(err, ErrInsufficientStock) {
		t.Fatalf("overspend: %v", err)
	}
	if err = r.DeleteFirewoodProcessing(ctx, org.ID, p.ID); err != nil {
		t.Fatal(err)
	}
	s, err = r.GetFirewoodStock(ctx, org.ID)
	if err != nil || math.Abs(s.RawM3-8.2) > 1e-9 || s.SplitM3 != 0 {
		t.Fatalf("delete: %+v %v", s, err)
	}
	order, err := r.CreateOrder(ctx, org.ID, &domain.Order{MasterID: uid, ContractorID: cid, Status: domain.OrderStatusNew, FirewoodItems: []domain.FirewoodOrderItem{{Kind: "round", VolumeM3: 2, Price: 1500}}}, nil)
	if err != nil {
		t.Fatal(err)
	}
	if _, err = r.AddPayment(ctx, org.ID, order.ID, 1000, "аванс", uid); err != nil {
		t.Fatal(err)
	}
	if _, err = r.CompleteOrder(ctx, org.ID, order.ID, uid); err != nil {
		t.Fatal(err)
	}
	if _, err = r.CompleteOrder(ctx, org.ID, order.ID, uid); !errors.Is(err, ErrOrderClosed) {
		t.Fatalf("double complete: %v", err)
	}
	s, err = r.GetFirewoodStock(ctx, org.ID)
	if err != nil || s.RoundM3 != 1 {
		t.Fatalf("completed stock: %+v %v", s, err)
	}
	if err = r.DeleteFirewoodProcessing(ctx, org.ID, list[0].ID); !errors.Is(err, ErrInsufficientStock) {
		t.Fatalf("delete sold production: %v", err)
	}
	payments, err := r.GetOrderPayments(ctx, org.ID, order.ID)
	if err != nil || payments.TotalPrice != 3000 || payments.PaidAmount != 1000 {
		t.Fatalf("payments: %+v %v", payments, err)
	}
	debts, err := r.GetDebts(ctx, org.ID)
	if err != nil || len(debts) != 1 || debts[0].Due != 2000 {
		t.Fatalf("debts: %+v %v", debts, err)
	}
	lines, err := r.GetOrderLines(ctx, org.ID, order.ID)
	if err != nil || len(lines) != 1 || lines[0].FirewoodKind != "round" || lines[0].VolumeM3 != 2 {
		t.Fatalf("PDF lines: %+v %v", lines, err)
	}
	if _, err = r.AddPayment(ctx, org.ID, order.ID, 2000, "остаток", uid); err != nil {
		t.Fatal(err)
	}
	debts, err = r.GetDebts(ctx, org.ID)
	if err != nil || len(debts) != 0 {
		t.Fatalf("paid debts: %+v %v", debts, err)
	}
}

func TestOrganizationIsolation(t *testing.T) {
	url := os.Getenv("FIREWOOD_TEST_DATABASE_URL")
	if url == "" {
		t.Skip("Требуется отдельная тестовая база")
	}
	ctx := context.Background()
	db, err := pgxpool.New(ctx, url)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	r := NewRepository(db)
	demo, err := r.CreateOrganization(ctx, "Демо", "", true)
	if err != nil {
		t.Fatal(err)
	}
	prod, err := r.CreateOrganization(ctx, "Рабочая", "", false)
	if err != nil {
		t.Fatal(err)
	}
	user, err := r.CreateUser(ctx, "tg_900001", "tg_autogenerated", domain.RolePending)
	if err != nil {
		t.Fatal(err)
	}

	for _, org := range []*domain.Organization{demo, prod} {
		code := org.Name
		_, err := r.CreateInvite(ctx, org.ID, code, domain.RoleMaster, 1, time.Now().Add(time.Hour), 0)
		if err != nil {
			t.Fatal(err)
		}
		member, err := r.AcceptInvite(ctx, code, user.ID)
		if err != nil || member.OrganizationID != org.ID || member.Role != domain.RoleMaster {
			t.Fatalf("Членство: %+v, ошибка: %v", member, err)
		}
		if _, err := r.AcceptInvite(ctx, code, user.ID); !errors.Is(err, ErrInviteUnavailable) {
			t.Fatalf("Повторное использование приглашения: %v", err)
		}
		invites, err := r.ListOrganizationInvites(ctx, org.ID)
		if err != nil || len(invites) != 1 || invites[0].UsedCount != 1 {
			t.Fatalf("Приглашения: %+v, ошибка: %v", invites, err)
		}
		contractor, err := r.CreateContractor(ctx, org.ID, "Контрагент "+org.Name)
		if err != nil {
			t.Fatal(err)
		}
		order, err := r.CreateOrder(ctx, org.ID, &domain.Order{
			MasterID: user.ID, ContractorID: contractor.ID, Status: domain.OrderStatusNew,
		}, nil)
		if err != nil || order.OrderNumber != 1 {
			t.Fatalf("Первый заказ: %+v, ошибка: %v", order, err)
		}
	}
	if err := r.DeleteUser(ctx, demo.ID, user.ID); err != nil {
		t.Fatal(err)
	}
	if _, err := r.CreateInvite(ctx, demo.ID, "after-removal", domain.RoleWorker, 1, time.Now().Add(time.Hour), 0); err != nil {
		t.Fatal(err)
	}
	if _, err := r.AcceptInvite(ctx, "after-removal", user.ID); !errors.Is(err, ErrDeletedUser) {
		t.Fatalf("Приглашение для исключённого сотрудника: %v", err)
	}
	orgs, err := r.ListUserOrganizations(ctx, user.ID)
	if err != nil || len(orgs) != 1 || orgs[0].OrganizationID != prod.ID {
		t.Fatalf("Организации пользователя: %+v, ошибка: %v", orgs, err)
	}
	if err := r.ResetTestData(ctx, prod.ID); !errors.Is(err, ErrResetNotDemo) {
		t.Fatalf("Сброс рабочей организации: %v", err)
	}
	if err := r.ResetTestData(ctx, demo.ID); err != nil {
		t.Fatal(err)
	}
	for _, check := range []struct {
		orgID int64
		want  int
	}{{demo.ID, 0}, {prod.ID, 1}} {
		orders, err := r.GetOrders(ctx, check.orgID, 10, 0)
		if err != nil || len(orders) != check.want {
			t.Fatalf("Заказы организации %d: %+v, ошибка: %v", check.orgID, orders, err)
		}
		org, err := r.GetOrganizationByID(ctx, check.orgID)
		if err != nil || org.LastOrderNumber != int64(check.want) {
			t.Fatalf("Счётчик организации: %+v, ошибка: %v", org, err)
		}
	}
}
