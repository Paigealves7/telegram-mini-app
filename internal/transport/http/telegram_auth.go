package http

import (
	"encoding/json"
	"fmt"
	"log"
	"net/http"
	"time"

	"telegram-mini-app/internal/domain"
	"telegram-mini-app/internal/repository"
)

type TelegramAuthHandler struct {
	repo      *repository.Repository
	botToken  string
	jwtSecret []byte
}

func NewTelegramAuthHandler(repo *repository.Repository, botToken, jwtSecret string) *TelegramAuthHandler {
	return &TelegramAuthHandler{
		repo:      repo,
		botToken:  botToken,
		jwtSecret: []byte(jwtSecret),
	}
}

type TelegramAuthRequest struct {
	InitData  string `json:"init_data"`
	AuthDate  int64  `json:"auth_date"`
	UserID    int64  `json:"user_id"`
	Username  string `json:"username"`
	FirstName string `json:"first_name"`
	LastName  string `json:"last_name"`
}

func (h *TelegramAuthHandler) LoginViaTelegram(w http.ResponseWriter, r *http.Request) {
	var req TelegramAuthRequest
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		http.Error(w, "некорректное тело запроса", http.StatusBadRequest)
		return
	}

	log.Printf("TG AUTH: user_id=%d, username=%s, auth_date=%d",
		req.UserID, req.Username, req.AuthDate)

	// === ПРОВЕРКА 1: user_id обязателен ===
	if req.UserID == 0 {
		log.Printf("TG AUTH: user_id отсутствует")
		http.Error(w, "user_id missing", http.StatusBadRequest)
		return
	}

	// === ПРОВЕРКА 2: auth_date не старше 1 часа (3600 секунд) ===
	// Защита от replay-атак со старыми initData
	const maxAgeSeconds = 3600
	now := time.Now().Unix()
	if req.AuthDate == 0 {
		log.Printf("TG AUTH: auth_date отсутствует")
		http.Error(w, "auth_date missing", http.StatusBadRequest)
		return
	}
	age := now - req.AuthDate
	if age < 0 || age > maxAgeSeconds {
		log.Printf("TG AUTH: auth_date устарел (age=%d секунд, max=%d)", age, maxAgeSeconds)
		http.Error(w, "auth_date expired", http.StatusUnauthorized)
		return
	}

	// === ПРОВЕРКА 3: initData не пустой (базовая валидация) ===
	if req.InitData == "" {
		log.Printf("TG AUTH: init_data пустой")
		http.Error(w, "init_data missing", http.StatusBadRequest)
		return
	}

	// === Всё ок — ищем или создаём пользователя ===
	username := fmt.Sprintf("tg_%d", req.UserID)

	user, err := h.repo.GetUserByUsername(r.Context(), username)
	if err != nil {
		log.Printf("TG AUTH: пользователь %s не найден, создаём", username)
		user, err = h.repo.CreateUser(r.Context(), username, "tg_autogenerated", domain.RoleWorker)
		if err != nil {
			log.Printf("TG AUTH: ошибка создания пользователя: %v", err)
			http.Error(w, "не удалось зарегистрировать пользователя Telegram", http.StatusInternalServerError)
			return
		}
	}

	// === Генерируем JWT ===
	claims := &Claims{
		UserID: user.ID,
		Role:   string(user.Role),
	}

	tokenString, err := generateToken(claims, h.jwtSecret)
	if err != nil {
		log.Printf("TG AUTH: ошибка генерации JWT: %v", err)
		http.Error(w, "ошибка генерации токена", http.StatusInternalServerError)
		return
	}

	log.Printf("TG AUTH: успешный вход для %s (id=%d)", username, user.ID)

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(map[string]string{
		"token": tokenString,
	})
}
