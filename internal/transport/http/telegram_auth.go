package http

import (
	"encoding/json"
	"errors"
	"fmt"
	"log"
	"net/http"
	"strings"
	"time"

	"telegram-mini-app/internal/domain"
	"telegram-mini-app/internal/repository"
	"telegram-mini-app/pkg/telegram"
)

const (
	// Как долго initData считается свежим. Токен сессии живёт 24 часа,
	// поэтому окно такое же: Mini App, восстановленный из фона, не должен вылетать.
	initDataMaxAge = 24 * time.Hour

	// Маркер вместо хеша пароля у аккаунтов, созданных через Telegram.
	// Bcrypt-хеш всегда начинается с «$2», так что префикс «tg_» отличает их надёжно.
	tgPasswordMarker = "tg_autogenerated"
	tgPasswordPrefix = "tg_"
)

type TelegramAuthHandler struct {
	repo      *repository.Repository
	botToken  string
	jwtSecret []byte
}

func NewTelegramAuthHandler(repo *repository.Repository, botToken, jwtSecret string) *TelegramAuthHandler {
	return &TelegramAuthHandler{
		repo:      repo,
		botToken:  botToken,
		jwtSecret: []byte(jwtSecret),
	}
}

// Из тела запроса используется ТОЛЬКО init_data.
// Всё остальное (id, имя, дата) берётся из подписанных данных Telegram.
type TelegramAuthRequest struct {
	InitData string `json:"init_data"`
}

func (h *TelegramAuthHandler) LoginViaTelegram(w http.ResponseWriter, r *http.Request) {
	r.Body = http.MaxBytesReader(w, r.Body, 16<<10)

	var req TelegramAuthRequest
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil || req.InitData == "" {
		http.Error(w, "некорректное тело запроса", http.StatusBadRequest)
		return
	}

	data, err := telegram.ValidateInitData(req.InitData, h.botToken, initDataMaxAge, time.Now())
	if err != nil {
		log.Printf("TG AUTH: вход отклонён: %v (remote=%s)", err, r.RemoteAddr)
		if errors.Is(err, telegram.ErrEmptyToken) {
			http.Error(w, "ошибка конфигурации сервера", http.StatusInternalServerError)
			return
		}
		http.Error(w, "ошибка авторизации Telegram", http.StatusUnauthorized)
		return
	}

	username := fmt.Sprintf("tg_%d", data.User.ID)

	user, err := h.repo.GetUserByUsername(r.Context(), username)
	if err != nil {
		created, createErr := h.repo.CreateUser(r.Context(), username, tgPasswordMarker, domain.RoleWorker)
		if createErr == nil {
			user = created // свежий Telegram-аккаунт; PasswordHash в ответе CreateUser пустой
		} else {
			// Два первых входа одновременно: второй упёрся в UNIQUE. Берём уже созданного.
			user, err = h.repo.GetUserByUsername(r.Context(), username)
			if err != nil {
				log.Printf("TG AUTH: не удалось создать пользователя %s: %v", username, createErr)
				http.Error(w, "не удалось зарегистрировать пользователя Telegram", http.StatusInternalServerError)
				return
			}
		}
	}

	// Аккаунт с таким именем мог быть заранее создан через /auth/register с обычным паролем.
	// Пускать в него по Telegram нельзя.
	if user.PasswordHash != "" && !strings.HasPrefix(user.PasswordHash, tgPasswordPrefix) {
		log.Printf("TG AUTH: аккаунт %s создан не через Telegram, вход запрещён", username)
		http.Error(w, "доступ запрещён", http.StatusForbidden)
		return
	}

	claims := &Claims{
		UserID: user.ID,
		Role:   string(user.Role),
	}

	tokenString, err := generateToken(claims, h.jwtSecret)
	if err != nil {
		log.Printf("TG AUTH: ошибка генерации JWT: %v", err)
		http.Error(w, "ошибка генерации токена", http.StatusInternalServerError)
		return
	}

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(map[string]string{
		"token": tokenString,
	})
}
